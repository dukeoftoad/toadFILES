package com.toadfiles.app.ui.whatsnew

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/** One `### Section` of a release with its `- ` bullet items, in file order. */
data class ChangelogSection(
    val title: String,
    val items: List<String>,
)

/** One `## [version] — date` release and its sections, newest first as parsed. */
data class ChangelogRelease(
    val version: String,
    /** ISO date as written in the changelog (e.g. "2026-11-02"); null when absent. */
    val date: String?,
    val sections: List<ChangelogSection>,
) {
    /** All bullet items across sections, in order — for short previews. */
    val allItems: List<String>
        get() = sections.flatMap { it.items }
}

/**
 * Minimal Keep-a-Changelog 1.1.0 parser for the changelog bundled with the APK.
 *
 * The asset is generated at build time from the repository's CHANGELOG.md (Gradle
 * `syncChangelog`), so release notes live in exactly one place. The parser is
 * deliberately forgiving:
 *  - `## [Unreleased]` is skipped, as are `[x.y.z]: https://…` link footers,
 *    the `# ` document title, prose and anything else it does not recognize;
 *  - the date after the dash is optional (missing dates become null);
 *  - bullets may wrap over several lines — continuations are folded into the item;
 *  - `**bold**` markers, `` `code` `` ticks and `[text](url)` links are flattened
 *    to plain text for display;
 *  - a bullet before any `###` heading lands in a "Changes" section;
 *  - unparsable content yields an empty list, never a crash.
 */
object Changelog {

    /** Asset name generated by the Gradle `syncChangelog` task. */
    const val ASSET_NAME = "changelog.md"

    private val RELEASE_HEADING = Regex("""^##\s+\[([^\]]+)\](?:\s*[-–—]\s*(\S+))?(?:\s*[-–—])?\s*$""")
    private val SECTION_HEADING = Regex("""^###\s+(.+?)\s*$""")
    private val BULLET = Regex("""^[-*]\s+(.+)$""")
    private val LINK_FOOTER = Regex("""^\[[^\]]+\]:\s*\S+""")
    private val MD_LINK = Regex("""\[([^\]]+)]\(([^)]+)\)""")

    /** Reads and parses the bundled asset; empty list when it is missing or unparsable. */
    suspend fun fromAssets(context: Context): List<ChangelogRelease> = withContext(Dispatchers.IO) {
        try {
            parse(context.assets.open(ASSET_NAME).bufferedReader().use { it.readText() })
        } catch (_: Exception) {
            emptyList()
        }
    }

    /**
     * Parses Keep-a-Changelog markdown into releases (newest first, matching the
     * file's order). Pure function — no Android types — so tests can exercise it
     * directly against fixtures.
     */
    fun parse(markdown: String): List<ChangelogRelease> {
        val releases = mutableListOf<ChangelogRelease>()

        var version: String? = null
        var date: String? = null
        val sectionTitles = mutableListOf<String>()
        val sectionItems = mutableListOf<MutableList<String>>()

        fun flush() {
            val v = version ?: return
            if (sectionTitles.isEmpty()) return // a release with no items carries no signal
            releases += ChangelogRelease(
                version = v,
                date = date,
                sections = sectionTitles.mapIndexed { i, title ->
                    ChangelogSection(title, sectionItems[i].toList())
                },
            )
            version = null
            date = null
            sectionTitles.clear()
            sectionItems.clear()
        }

        fun appendBullet(rawItem: String) {
            val item = flattenMarkdown(rawItem)
            if (item.isEmpty()) return
            if (sectionTitles.isEmpty()) {
                sectionTitles += "Changes"
                sectionItems += mutableListOf()
            }
            sectionItems.last() += item
        }

        for (raw in markdown.lineSequence()) {
            val line = raw.trimEnd()
            when {
                line.isBlank() -> Unit

                line.startsWith("## ") -> {
                    flush()
                    val match = RELEASE_HEADING.matchEntire(line.trim())
                    if (match != null) {
                        val v = match.groupValues[1].trim()
                        if (v.equals("Unreleased", ignoreCase = true)) {
                            version = null // work-in-progress notes are not a release
                        } else {
                            version = v
                            date = match.groupValues[2].ifBlank { null }
                        }
                    }
                }

                // Before the first release heading (document title, intro prose), or
                // inside [Unreleased] — nothing there becomes release content.
                version == null -> Unit

                line.startsWith("### ") -> {
                    val title = SECTION_HEADING.matchEntire(line.trim())?.groupValues?.get(1)?.trim()
                    if (!title.isNullOrBlank()) {
                        sectionTitles += title
                        sectionItems += mutableListOf()
                    }
                }

                LINK_FOOTER.matches(line.trim()) -> Unit // [1.9.0]: https://… compare links

                else -> {
                    val trimmed = line.trim()
                    val bullet = BULLET.matchEntire(trimmed)
                    when {
                        bullet != null -> appendBullet(bullet.groupValues[1])
                        // Wrapped continuation of the previous bullet; with no open
                        // bullet yet, standalone prose is ignored.
                        sectionItems.isNotEmpty() && sectionItems.last().isNotEmpty() -> {
                            val items = sectionItems.last()
                            items[items.lastIndex] = items.last() + " " + flattenMarkdown(trimmed)
                        }
                    }
                }
            }
        }
        flush()
        return releases
    }

    /** Flattens the markdown this app writes into display text; blank results are dropped. */
    private fun flattenMarkdown(text: String): String = text
        .replace(MD_LINK) { m -> m.groupValues[1] }
        .replace("**", "")
        .replace("`", "")
        .trim()
}
